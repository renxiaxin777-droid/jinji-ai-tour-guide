def with_hardcore(a, level="basic"):
    """导览模式分层：basic 原样；pro 加建筑形制；hardcore / planner 再加断代依据 + 冷知识争议。
    planner（行程规划师）档的提示词要求「逐构件读古建」并讲学术争议，故与 hardcore 同享完整字段。"""
    d = dict(a)
    if level in ("pro", "hardcore", "planner") and a["name"] in HARDCORE:
        d["arch"] = HARDCORE[a["name"]]["arch"]
    if level in ("hardcore", "planner") and a["name"] in HARDCORE:
        d["dating"] = HARDCORE[a["name"]]["dating"]
        d["debate"] = HARDCORE[a["name"]]["debate"]
    return d


def pref_of(city):
    """从『市+县』拼接格式（如 运城新绛）提取地级市：最长前缀匹配"""
    hit = ""
    for c in ALL_CITIES:
        if city.startswith(c) and len(c) > len(hit):
            hit = c
    return hit or city


def build_itinerary(days, city="", interests=""):
    """按 城市/区域 + 兴趣主题 从知识库动态编排行程（任意组合可用）"""
    days = max(1, min(int(days), 5))
    pool = []
    for a in ATTRACTIONS:
        c = pref_of(a["city"])
        if interests:
            wukong_mode = any(w in interests for w in ("黑神话", "取景", "悟空"))
            if wukong_mode:
                if not a["wukong"]:
                    continue
            else:
                keys = [interests[i:i + 2] for i in range(len(interests) - 1)]
                blob = " ".join(a["tags"]) + a["name"] + a["summary"]
                if keys and not any(k in blob for k in keys):
                    continue
        if city:
            region = next((r for r in REGIONS if city in r or r in city), None)
            if region:
                if c not in REGIONS[region]:
                    continue
            elif not (city in c or c in city or city in a["city"] or a["city"] in city):
                continue
        pool.append(a)

    if not pool:
        # 城市不在覆盖范围 → 明确告知（旧逻辑会静默返回全省默认景点，例如问"北京"也答山西）
        if city:
            _loose = [a for a in ATTRACTIONS
                      if pref_of(a["city"]) == pref_of(city) or city in a["city"]]
            if not _loose:
                _covered = "、".join(REGIONS.keys()) + "，以及太原、晋中、临汾、运城、晋城等地"
                return {"命中": 0, "天数": days,
                        "提示": f"知识库暂未覆盖「{city}」。当前覆盖区域：{_covered}。"
                                "可以换个城市，或直接询问已收录的山西古建。"}
            pool = _loose          # 在城市覆盖内、只是兴趣词没匹配上 → 放宽为按城市编排
        else:
            pool = ATTRACTIONS[: max(days * 2, 4)]

    def region_idx(a):
        c = pref_of(a["city"])
        for i, cities in enumerate(REGIONS.values()):
            if c in cities:
                return i
        return 9

    pool = sorted(pool, key=lambda a: (region_idx(a), ATTRACTIONS.index(a)))

    per = max(2, min(3, -(-len(pool) // days)))
    it, idx = [], 0
    for d in range(1, days + 1):
        chunk = pool[idx: idx + per]
        idx += per
        if not chunk:
            break
        cities_day = sorted({pref_of(a["city"]) for a in chunk})
        route = " → ".join(f"{a['name']}（{a['era'].split('（')[0]}）" for a in chunk)
        it.append({"day": d, "title": " · ".join(cities_day), "route": route,
                   "stay": ("宿" + cities_day[-1]) if d < days else "返程"})
        if idx >= len(pool):
            break
    rest = [a["name"] for a in pool[idx:]] if idx < len(pool) else []
    if not it:
        it = [{"day": 1, "title": "太原", "route": "晋祠 → 永祚寺", "stay": "当日往返"}]
    covered = sorted({pref_of(a["city"]) for a in pool})
    out = {"推荐路线": f"山西古建 {len(it)} 日（动态编排）", "天数": len(it),
           "覆盖城市": covered, "行程": it,
           "说明": f"由知识库景点按区域相邻原则动态编排，每日 {per} 处并留出交通与用餐时间；"
                   "请大模型润色成文，并说明这是行程草案，不含实时车程与开放信息"}
    if rest:
        out["未排入的备选"] = rest[:12]
        out["备选说明"] = f"另有 {len(rest)} 处因天数限制未排入，可增加天数或按同城顺路安排"
    return out


def _blob(a):
    return " ".join([a["name"]] + a["aliases"] + [a["city"], a["era"]] + a["tags"] + [a["summary"]])


def retrieve(query, top_k=3):
    """关键词+二字词元双通道检索，返回相关度最高的 top_k 条"""
    q = str(query)
    scored = []
    for a in ATTRACTIONS:
        b = _blob(a)
        s = 0
        if a["name"] in q or (q.strip() and q.strip() in a["name"]):
            s += 12
        for al in a["aliases"]:
            if al and (al in q or q.strip() in al):
                s += 10
        for t in a["tags"]:
            if t in q:
                s += 5
        if a["city"] in q:
            s += 4
        if any(w in q for w in ("黑神话", "取景", "悟空")):
            if a["wukong"]:
                s += 8
        # 二字词元模糊匹配
        for i in range(len(q) - 1):
            if q[i:i + 2] in b:
                s += 1
        if s:
            scored.append((s, a))
    scored.sort(key=lambda x: -x[0])
    return [a for _, a in scored[:top_k]]


def find_attraction(name):
    """按名称精确/模糊查找单个景点"""
    for a in ATTRACTIONS:
        if name in a["name"] or any(name in al for al in a["aliases"]):
            return a
    return None
